#!/usr/bin/env bash
# Writes supabase/setup.sql: every migration in order, in one transaction, for
# pasting into the Supabase SQL Editor once on a new project. Re-run after
# adding a migration (pnpm db:test fails while setup.sql is out of date).
# Usage: supabase/bundle.sh [output]   (default: supabase/setup.sql)
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
out="${1:-$here/setup.sql}"
{
  echo "-- Crumble POS: full database setup for a NEW Supabase project."
  echo "-- Generated by supabase/bundle.sh from supabase/migrations. Do not edit."
  echo "-- Paste the whole file into SQL Editor and run it once. Everything runs in"
  echo "-- one transaction: on any error nothing is applied."
  echo
  echo "begin;"
  for f in "$here"/migrations/*.sql; do
    echo
    echo "-- ===== $(basename "$f") ====="
    cat "$f"
  done
  echo
  echo "commit;"
} > "$out"
